const (
	agentKeysName   = "TURING_AGENT_API_KEYS"
	agentKeysPrefix = agentKeysName + "."
	// maxAgentNameRunes is the services' limit on a credential name.
	maxAgentNameRunes = 64

	secretsOffTheCommandLine = "secrets are never taken on the command line; use --stdin or answer the prompt"
)

var errAgentKeysUnreadable = errors.New(agentKeysName + " in .env is not a JSON object of names and keys; clear it with ./turing config unset " +
	agentKeysName + ", then add each agent again")

// setting is what a config command names: a registry key, or one agent's
// entry in the agent key map.
type setting struct {
	key     registry.Key
	agent   string
	isAgent bool
}

func (s setting) label() string {
	if s.isAgent {
		return agentKeysPrefix + s.agent
	}
	return s.key.Name
}

func (s setting) secret() bool {
	return s.isAgent || s.key.IsSecret()
}

// config shows and changes the settings in .env. With no arguments it is a
// menu.
func (e Env) config(ctx context.Context, args []string) int {
	if len(args) == 0 {
		return e.configMenu(ctx)
	}
	command, rest := args[0], args[1:]
	switch command {
	case "show":
		return e.configShow(rest)
	case "get":
		return e.configGet(rest)
	case "set":
		return e.configSet(ctx, rest)
	case "unset":
		return e.configUnset(ctx, rest)
	case "help", "-h", "--help":
		_, _ = io.WriteString(e.Stdout, Usage)
		return 0
	default:
		return e.usageError("unknown config command %q; run ./turing help", command)
	}
}

type configArgs struct {
	positional          []string
	stdin, yes, noApply bool
}

// parseConfigArgs reads a config command's arguments, taking the named
// options before or after the setting. A value that begins with - goes after
// --, unless it is a negative number.
func (e Env) parseConfigArgs(command string, args []string, options ...string) (configArgs, int, bool) {
	var parsed configArgs
	flags := map[string]*bool{"stdin": &parsed.stdin, "yes": &parsed.yes, "no-apply": &parsed.noApply}
	optionsEnded := false
	for _, arg := range args {
		switch {
		case optionsEnded || !strings.HasPrefix(arg, "-") || arg == "-" || isNegativeNumber(arg):
			parsed.positional = append(parsed.positional, arg)
		case arg == "--":
			optionsEnded = true
		case arg == "-h" || arg == "--help":
			_, _ = io.WriteString(e.Stdout, Usage)
			return parsed, 0, false
		default:
			name := strings.TrimPrefix(strings.TrimPrefix(arg, "-"), "-")
			if !slices.Contains(options, name) {
				// The argument is not quoted: set's value comes last, so it can be a secret.
				return parsed, e.usageError("turing config %s: unknown option (an argument that begins with -); a value that begins with - goes after --; run ./turing help", command), false
			}
			*flags[name] = true
		}
	}
	return parsed, 0, true
}

func isNegativeNumber(arg string) bool {
	return len(arg) > 1 && arg[0] == '-' && arg[1] >= '0' && arg[1] <= '9'
}

// resolveSetting finds the setting a command names. A name config does not
// change is refused with where it is changed instead.
func (e Env) resolveSetting(name string) (setting, int, bool) {
	if agent, ok := strings.CutPrefix(name, agentKeysPrefix); ok {
		key, _ := registry.Lookup(agentKeysName)
		return setting{key: key, agent: agent, isAgent: true}, 0, true
	}
	key, ok := registry.Lookup(name)
	if !ok {
		for _, candidate := range registry.All() {
			if slices.Contains(candidate.Deprecated, name) {
				return setting{}, e.usageError("%s is the old name of %s; run the command again with %s", name, candidate.Name, candidate.Name), false
			}
		}
		return setting{}, e.usageError("unknown setting %q; ./turing config show lists the settings", name), false
	}
	if !key.Editable {
		return setting{}, e.fail("%s", homeOf(key)), false
	}
	return setting{key: key}, 0, true
}

// homeOf says where a key config does not change is changed instead.
func homeOf(key registry.Key) string {
	const rest = "so turing config does not handle it; ./turing config show lists the settings it does"
	switch {
	case key.Name == clientKey:
		return clientKey + " is the app's key, which turing config does not handle; ./turing connect shows it and ./turing connect --rotate-key replaces it"
	case key.Generated:
		return key.Name + " is generated by ./scripts/init.sh and never changed by hand, " + rest
	case key.Name == "TURING_MAX_CONCURRENT_RUNS_GENERAL":
		return key.Name + " stays 1 until AGT-000 supplies the evidence to raise it, " + rest
	default:
		return key.Name + " is internal wiring that ./scripts/init.sh writes or the compose file sets, " + rest
	}
}

// sectionKeys returns the editable keys of a section, in registry order.
func sectionKeys(section string) []registry.Key {
	var keys []registry.Key
	for _, key := range registry.Editable() {
		if key.Section == section {
			keys = append(keys, key)
		}
	}
	return keys
}

// readExample reads .env.example, where each setting's description and
// shipped value come from. Without it, both are blank.
func (e Env) readExample() []byte {
	data, err := os.ReadFile(filepath.Join(e.BackendDir, ".env.example"))
	if err != nil {
		return nil
	}
	return data
}

// currentValue is what may be shown of a setting in .env: a secret as set or
// not set, and the agent key map by its names. It is "" only for an empty
// setting that is not a secret.
func currentValue(key registry.Key, file *envfile.File) string {
	value := envValue(file, key.Name)
	switch {
	case key.Kind == registry.SecretMap:
		keys, err := decodeAgentKeys(value)
		if err != nil {
			return "set, but not readable as names and keys"
		}
		if len(keys) == 0 {
			return "not set"
		}
		return strings.Join(slices.Sorted(maps.Keys(keys)), ", ")
	case key.IsSecret():
		if value == "" {
			return "not set"
		}
		return "set"
	}
	return value
}

func (e Env) configShow(args []string) int {
	parsed, code, ok := e.parseConfigArgs("show", args)
	if !ok {
		return code
	}
	if len(parsed.positional) > 0 {
		return e.usageError("turing config show takes no arguments, got %q; run ./turing help", parsed.positional[0])
	}
	file, err := e.readDotEnv()
	if err != nil {
		return e.fail("%v", err)
	}
	example := e.readExample()
	for i, section := range registry.Sections {
		if i > 0 {
			_, _ = fmt.Fprintln(e.Stdout)
		}
		_, _ = fmt.Fprintln(e.Stdout, section)
		for _, key := range sectionKeys(section) {
			shown := currentValue(key, file)
			if shown == "" {
				shown = "(empty)"
				if shipped := registry.Shipped(example, key.Name); shipped != "" {
					shown = "(empty; shipped value: " + shipped + ")"
				}
			}
			_, _ = fmt.Fprintf(e.Stdout, "  %s = %s\n", key.Name, shown)
		}
	}
	_, _ = fmt.Fprintln(e.Stdout, "\nChange one with ./turing config set KEY VALUE, or run ./turing config for a menu.")
	return 0
}

func (e Env) configGet(args []string) int {
	parsed, code, ok := e.parseConfigArgs("get", args)
	if !ok {
		return code
	}
	if len(parsed.positional) != 1 {
		return e.usageError("turing config get takes one setting; run ./turing help")
	}
	s, code, ok := e.resolveSetting(parsed.positional[0])
	if !ok {
		return code
	}
	if s.secret() {
		return e.fail("%s is a secret; ./turing config show says whether it is set", s.label())
	}
	file, err := e.readDotEnv()
	if err != nil {
		return e.fail("%v", err)
	}
	_, _ = fmt.Fprintln(e.Stdout, envValue(file, s.key.Name))
	return 0
}

func (e Env) configSet(ctx context.Context, args []string) int {
	parsed, code, ok := e.parseConfigArgs("set", args, "stdin", "yes", "no-apply")
	if !ok {
		return code
	}
	if n := len(parsed.positional); n < 1 || n > 2 {
		return e.usageError("turing config set takes a setting and, unless it is a secret, its value; run ./turing help")
	}
	s, code, ok := e.resolveSetting(parsed.positional[0])
	if !ok {
		return code
	}
	given := len(parsed.positional) == 2
	switch {
	case given && s.secret():
		// Shell history and ps would keep it.
		return e.usageError("%s", secretsOffTheCommandLine)
	case s.key.Kind == registry.SecretMap && !s.isAgent:
		return e.usageError("%s is changed one agent at a time; run ./turing config set %s<name>", agentKeysName, agentKeysPrefix)
	case given && parsed.stdin:
		return e.usageError("give the value or --stdin, not both; run ./turing help")
	case s.isAgent && !validAgentName(s.agent):
		return e.fail("%s", invalidAgentName(s.agent))
	}

	var value string
	if given {
		value = parsed.positional[1]
	} else if value, code, ok = e.readValue(s, parsed.stdin); !ok {
		return code
	}
	opts := saveOptions{Yes: parsed.yes, NoApply: parsed.noApply}
	if s.isAgent {
		if value == "" {
			return e.fail("the key for %s is empty; to remove that agent, run ./turing config unset %s", s.agent, s.label())
		}
		return e.saveEdit(ctx, agentKeyEdit(s.agent, &value), opts)
	}
	// An empty answer is a slip, such as Enter at a prompt or an empty pipe,
	// not a request to clear the setting; only a VALUE typed as "" is.
	if value == "" && !given {
		return e.usageError("no value was given for %s, so nothing changed; to clear it, run ./turing config unset %s", s.label(), s.label())
	}
	return e.saveSettings(ctx, map[string]*string{s.key.Name: &value}, opts)
}

// readValue reads a value the command line did not give: one line from
// standard input with --stdin, otherwise from the person at the terminal,
// with typing hidden for a secret.
func (e Env) readValue(s setting, fromStdin bool) (string, int, bool) {
	if fromStdin {
		line, err := e.readLine()
		if err != nil && line == "" {
			if errors.Is(err, io.EOF) {
				return "", e.usageError("nothing was read from standard input for %s; pipe the value in, as in printf '%%s\\n' VALUE | ./turing config set %s --stdin",
					s.label(), s.label()), false
			}
			return "", e.fail("could not read standard input: %v; run the command again", err), false
		}
		return line, 0, true
	}
	if !e.IsTerminal {
		how := "give it after the name, or pipe it in with --stdin"
		if s.secret() {
			how = "pipe it in with --stdin"
		}
		return "", e.usageError("%s needs a value: %s", s.label(), how), false
	}
	if s.secret() {
		value, err := e.ReadSecret(fmt.Sprintf("Value for %s (typing is hidden): ", s.label()))
		if err != nil {
			return "", e.fail("could not read the value: %v; run the command again", err), false
		}
		return value, 0, true
	}
	_, _ = fmt.Fprintf(e.Stdout, "Value for %s: ", s.label())
	line, err := e.readLine()
	if err != nil && line == "" {
		_, _ = fmt.Fprintln(e.Stdout)
		return "", e.fail("no value was given for %s, so nothing changed", s.label()), false
	}
	return line, 0, true
}

func (e Env) configUnset(ctx context.Context, args []string) int {
	parsed, code, ok := e.parseConfigArgs("unset", args, "yes", "no-apply")
	if !ok {
		return code
	}
	if len(parsed.positional) != 1 {
		return e.usageError("turing config unset takes one setting; run ./turing help")
	}
	s, code, ok := e.resolveSetting(parsed.positional[0])
	if !ok {
		return code
	}
	opts := saveOptions{Yes: parsed.yes, NoApply: parsed.noApply}
	if s.isAgent {
		if !validAgentName(s.agent) {
			return e.fail("%s", invalidAgentName(s.agent))
		}
		return e.saveEdit(ctx, agentKeyEdit(s.agent, nil), opts)
	}
	empty := ""
	return e.saveSettings(ctx, map[string]*string{s.key.Name: &empty}, opts)
}

// decodeAgentKeys reads the agent key map; empty is no agents. Its error
// never quotes the value, which is a list of keys.
func decodeAgentKeys(raw string) (map[string]string, error) {
	keys := map[string]string{}
	if raw == "" {
		return keys, nil
	}
	if err := json.Unmarshal([]byte(raw), &keys); err != nil {
		return nil, errAgentKeysUnreadable
	}
	if keys == nil {
		keys = map[string]string{}
	}
	return keys, nil
}

// agentKeyEdit sets one agent's key, or removes the agent when key is nil,
// in the map as .env holds it under the lock, so no other agent is lost.
func agentKeyEdit(name string, key *string) settingsEdit {
	return func(current *envfile.File) (map[string]*string, error) {
		keys, err := decodeAgentKeys(envValue(current, agentKeysName))
		if err != nil {
			return nil, err
		}
		if key == nil {
			if _, ok := keys[name]; !ok {
				return nil, fmt.Errorf("%s has no agent named %q; ./turing config show lists the names", agentKeysName, name)
			}
			delete(keys, name)
		} else {
			keys[name] = *key
		}
		value := ""
		if len(keys) > 0 {
			encoded, err := json.Marshal(keys)
			if err != nil {
				return nil, err
			}
			value = string(encoded)
		}
		return map[string]*string{agentKeysName: &value}, nil
	}
}

// validAgentName is the services' rule for a credential name.
func validAgentName(name string) bool {
	if name == "" || len([]rune(name)) > maxAgentNameRunes {
		return false
	}
	for _, character := range name {
		switch {
		case character >= 'a' && character <= 'z',
			character >= 'A' && character <= 'Z',
			character >= '0' && character <= '9',
			character == '_', character == '-', character == '.':
		default:
			return false
		}
	}
	return true
}

func invalidAgentName(name string) string {
	return fmt.Sprintf("%q is not a valid agent name: use letters, digits, _, - and ., at most %d of them; run the command again with another name",
		name, maxAgentNameRunes)
}
